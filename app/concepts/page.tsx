'use client';

import React, { useEffect } from 'react';
import { useRouter } from 'next/navigation';
import confetti from 'canvas-confetti';
import { useEvent } from '@/lib/context/EventContext';
import { ConceptCard } from '@/components/concepts/ConceptCard';
import { EmptyState } from '@/components/ui/EmptyState';
import { Sparkles, ArrowRight, Calendar, DollarSign, Users, MapPin } from 'lucide-react';
import { Button } from '@/components/ui/Button';

export default function ConceptsPage() {
  const router = useRouter();
  const { brief, planSuite, selectedConceptId, selectConcept } = useEvent();

  useEffect(() => {
    if (planSuite && planSuite.concepts.length > 0) {
      try {
        const prefersReducedMotion =
          typeof window !== 'undefined' &&
          window.matchMedia('(prefers-reduced-motion: reduce)').matches;
        if (!prefersReducedMotion) {
          confetti({
            particleCount: 40,
            spread: 60,
            origin: { y: 0.6 },
            disableForReducedMotion: true,
          });
        }
      } catch {
        // Safe degrade if canvas is unsupported
      }
    }
  }, [planSuite]);

  if (!planSuite || !brief || planSuite.concepts.length === 0) {
    return (
      <div className="max-w-4xl mx-auto px-4 py-16">
        <EmptyState
          title="No Celebration Concepts Available"
          description="Complete the event brief wizard to generate three personalized, feasible celebration archetypes with minute-by-minute schedules and budgets."
          actionText="Start Event Brief Wizard"
          actionHref="/planner"
        />
      </div>
    );
  }

  const handleSelectAndProceed = (conceptId: string) => {
    selectConcept(conceptId);
    router.push('/workspace');
  };

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-12">
      {/* Header & Brief Recap */}
      <div className="flex flex-col md:flex-row md:items-end justify-between gap-6 border-b border-[#e5e5ea] pb-8 mb-10">
        <div>
          <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-[#0071e3]/10 text-[#0071e3] text-xs font-semibold mb-3">
            <Sparkles className="w-3.5 h-3.5" />
            <span>3 Curated Celebration Archetypes</span>
          </div>
          <h1 className="text-3xl sm:text-4xl font-bold text-[#1d1d1f] tracking-tight">
            {brief.eventTitle}
          </h1>
          <p className="text-sm text-[#555555] mt-1.5 max-w-2xl leading-relaxed">
            Review the 3 tailored concepts generated by CelebrationPilot AI. Selecting a concept
            synchronizes your master schedule, category budgets, and vendor checklists.
          </p>
        </div>

        {/* Brief Metrics Pills */}
        <div className="flex flex-wrap items-center gap-2 text-xs">
          <div className="flex items-center gap-1.5 px-3 py-1.5 rounded-full bg-white border border-[#e5e5ea] text-[#555555] shadow-2xs">
            <Calendar className="w-3.5 h-3.5 text-[#0071e3]" />
            <span className="font-medium">{brief.targetDate}</span>
          </div>
          <div className="flex items-center gap-1.5 px-3 py-1.5 rounded-full bg-white border border-[#e5e5ea] text-[#555555] shadow-2xs">
            <MapPin className="w-3.5 h-3.5 text-[#0071e3]" />
            <span className="font-medium">{brief.city}</span>
          </div>
          <div className="flex items-center gap-1.5 px-3 py-1.5 rounded-full bg-white border border-[#e5e5ea] text-[#555555] shadow-2xs">
            <Users className="w-3.5 h-3.5 text-[#0071e3]" />
            <span className="font-medium">{brief.guestCount} Guests</span>
          </div>
          <div className="flex items-center gap-1.5 px-3 py-1.5 rounded-full bg-white border border-[#e5e5ea] text-[#555555] shadow-2xs">
            <DollarSign className="w-3.5 h-3.5 text-[#0071e3]" />
            <span className="font-medium">{brief.currency} {brief.budgetTotal.toLocaleString()}</span>
          </div>
        </div>
      </div>

      {/* 3 Concept Cards Grid */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-8">
        {planSuite.concepts.map((concept) => (
          <ConceptCard
            key={concept.id}
            concept={concept}
            currency={brief.currency}
            isSelected={selectedConceptId === concept.id}
            onSelect={handleSelectAndProceed}
          />
        ))}
      </div>

      {/* Bottom CTA to jump to workspace */}
      <div className="mt-12 text-center pt-8 border-t border-[#e5e5ea]">
        <Button
          size="lg"
          variant="primary"
          onClick={() => router.push('/workspace')}
        >
          <span>Open Workspace for Selected Concept</span>
          <ArrowRight className="w-4 h-4 ml-2" />
        </Button>
      </div>
    </div>
  );
}
